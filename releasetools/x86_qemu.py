#!/usr/bin/env python3
#
# x86_qemu.py - headless MINIX i386 QEMU test harness
#
# Boots minix_x86.img in QEMU via the multiboot path (kernel + modules from
# the release staging dir), redirects the MINIX console to a serial unix
# socket (boot arg console=tty00 => COM1, 115200 8N1), logs in as root
# (no password on stock images), optionally attaches an extra ext2 disk
# image built from a payload directory, runs shell commands inside the
# guest, and reports pass/fail via HARNESS markers in the serial log.
#
# This is the verification loop for all bare-metal-adjacent work that
# cannot run on the host (cross-compiled binaries, driver tests, ...).
#
# Usage:
#   x86_qemu.py [options] [--cmd "shell command" ...]
#
# Options:
#   --image PATH      boot disk image        (default: minix_x86.img in repo root)
#   --bootdir PATH    dir with kernel + mod* (default: ../obj.docker.i386 or ../obj.i386 destdir .temp)
#   --payload DIR     directory whose contents are put on the ext2 test disk
#   --cmd CMD         shell command to run in the guest (repeatable); each
#                     command's exit status is checked
#   --expect TEXT     literal text that must appear in guest output (repeatable)
#   --timeout SEC     overall timeout        (default: 240)
#   --screendump PPM  take a VGA screendump after the gate, before poweroff
#   --log FILE        serial log destination (default: x86_qemu.log)
#   --keep            leave qemu running after the commands (implies exit 0
#                     once commands are sent; for interactive debugging)
#   -h,--help         show this text
#
# Exit status: 0 when every --cmd returned 0 in the guest and every
# --expect text was seen; 1 otherwise; 2 on infrastructure failure
# (qemu/mke2fs missing, serial handshake failed, timeout).
#
# Guest-side flow (driven over serial):
#   login: -> "root" -> shell -> mkdir /mnt; mount /dev/c0d<N> /mnt
#   -> sh /mnt/minix-harness.sh  (generated; runs cmds.txt, prints markers)
#   -> host sends "poweroff"
#
# QEMU storage topology note: the boot disk is IDE (at_wini, /dev/c0d0).
# Extra IDE drives on other positions hang/error under at_wini in QEMU, so
# the test disk is attached via virtio-blk: the harness starts the in-guest
# virtio_blk service onto /dev/c1d0 (a virtio instance serves only minors
# 0..4, i.e. drive 0 of the c1 series), then mounts it — the same trick the
# ramdisk rc uses for virtio root disks, plus `virtio_blk=no` on the kernel
# cmdline so the rc does not mistake the test disk for the root device.
#
# Markers (searched in the serial log):
#   HARNESS:CMD:RC:<rc>:<cmd>   per command
#   HARNESS:DONE:<worst-rc>     end of run
#

import argparse
import os
import re
import shutil
import signal
import socket
import subprocess
import sys
import tempfile
import time

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Docker-built objdir is canonical since the docker/ workflow; fall back to a
# host build if that's what exists.
for _cand in ("obj.docker.i386", "obj.i386"):
    _p = os.path.normpath(os.path.join(REPO, "..", _cand))
    if os.path.isdir(_p):
        OBJ = _p
        break
else:
    OBJ = os.path.normpath(os.path.join(REPO, "..", "obj.docker.i386"))

GUEST_DRIVER = """\
#!/bin/sh
# generated by x86_qemu.py - do not edit
PATH=/sbin:/bin:/usr/sbin:/usr/bin
export PATH
echo HARNESS:START
worst=0
while IFS= read -r cmd; do
    [ -z "$cmd" ] && continue
    echo "HARNESS:CMD:START:$cmd"
    sh -c "$cmd"
    rc=$?
    echo "HARNESS:CMD:RC:$rc:$cmd"
    [ $rc -ne 0 ] && worst=$rc
done < /mnt/harness-cmds.txt
echo "HARNESS:DONE:$worst"
"""


def fail(msg):
    print(f"x86_qemu: {msg}", file=sys.stderr)
    sys.exit(2)


class QemuMinix:
    def __init__(self, args):
        self.args = args
        self.qemu = None
        self.serial = None
        self.buf = ""
        self.logf = open(args.log, "wb", buffering=0)

    def log(self, data: bytes):
        self.logf.write(data)
        sys.stdout.buffer.write(data)
        sys.stdout.buffer.flush()

    def spawn(self, testdisk):
        a = self.args
        bootdir = a.bootdir
        kernel = os.path.join(bootdir, "kernel")
        mods = sorted(f for f in os.listdir(bootdir) if f.startswith("mod"))
        if not os.path.exists(kernel) or not mods:
            fail(f"bootdir {bootdir} lacks kernel/mod* files")
        initrd = ",".join(mods)

        sockdir = tempfile.mkdtemp(prefix="x86_qemu-")
        self.sockdir = sockdir
        sersock = os.path.join(sockdir, "serial")
        monsock = os.path.join(sockdir, "monitor")

        append = "rootdevname=c0d0p0 console=tty00"
        extra = []
        if testdisk:
            # ramdisk rc defaults to treating a found virtio disk as the
            # root device; we boot from IDE and attach the virtio test disk
            # later, in-guest, on demand.
            append += " virtio_blk=no"
            extra += ["-drive",
                      f"file={testdisk},format=raw,if=none,id=testdisk",
                      "-device", "virtio-blk-pci,drive=testdisk"]

        cmd = [
            "qemu-system-i386",
            "-machine", "pc",
            "-m", "256",
            "-vga", "std",
            "-display", "none",
            "-no-reboot",
            "-serial", f"unix:{sersock},server=on,wait=off",
            "-monitor", f"unix:{monsock},server=on,wait=off",
            "-kernel", kernel,
            "-initrd", initrd,
            "-append", append,
            "-drive", f"file={a.image},format=raw,if=ide,index=0,media=disk",
        ] + extra
        accel = "kvm" if os.access("/dev/kvm", os.R_OK | os.W_OK) else "tcg"
        cmd += ["-accel", accel]

        env = dict(os.environ)
        self.errlog = tempfile.NamedTemporaryFile(prefix="x86_qemu-err-", delete=False)
        self.qemu = subprocess.Popen(cmd, env=env, cwd=bootdir,
                                     stdout=subprocess.DEVNULL,
                                     stderr=self.errlog)
        self.monsock = monsock
        self.serial = self._connect(sersock)
        self.serial.settimeout(0.5)

    def qemu_died(self):
        self.qemu.wait(timeout=2)
        err = ""
        try:
            err = open(self.errlog.name, "r", errors="replace").read().strip()
        except OSError:
            pass
        fail(f"qemu exited early (rc={self.qemu.returncode}): {err}")

    def _connect(self, path, tries=100):
        for _ in range(tries):
            s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
            try:
                s.connect(path)
                return s
            except OSError:
                s.close()
                if self.qemu.poll() is not None:
                    self.qemu_died()
                time.sleep(0.2)
        fail("could not connect to qemu serial socket")

    def pump(self, seconds):
        """Read serial output for up to `seconds`, appending to self.buf."""
        end = time.time() + seconds
        while time.time() < end:
            if self.qemu.poll() is not None:
                return False
            try:
                data = self.serial.recv(4096)
                if not data:
                    return False
                self.log(data)
                self.buf += data.decode("utf-8", "replace")
            except socket.timeout:
                pass
        return True

    def wait_for(self, pattern, timeout, what=""):
        end = time.time() + timeout
        while time.time() < end:
            if pattern in self.buf:
                return
            if not self.pump(0.5):
                time.sleep(0.2)
                if self.qemu.poll() is not None:
                    self.qemu_died()
        fail(f"timeout waiting for {what or pattern!r}")

    def wait_re(self, regex, timeout, what=""):
        r"""Like wait_for but takes a regex. Always prefer this for guest
        markers: echoed input contains the marker text with "$?" instead of
        digits, so requiring a \d suffix filters the echo out."""
        rx = re.compile(regex)
        end = time.time() + timeout
        while time.time() < end:
            if rx.search(self.buf):
                return
            if not self.pump(0.5):
                time.sleep(0.2)
                if self.qemu.poll() is not None:
                    self.qemu_died()
        fail(f"timeout waiting for {what or regex!r}")

    def send(self, text):
        self.serial.sendall(text.encode())

    def login(self, timeout):
        """Wait for getty's login prompt and log in as root, tolerating
        getty's input flush dropping early keystrokes.
        The root shell prompt is "<hostname># " (default "minix# ")."""
        prompt = re.compile(r"[\r\n]\S{0,15}# ")
        self.wait_for("login:", timeout, "login prompt")
        time.sleep(1.0)
        self.pump(1.0)
        for attempt in range(4):
            self.send("root\r")
            end = time.time() + 15
            while time.time() < end:
                if prompt.search(self.buf):
                    return
                self.pump(0.5)
            # no prompt - nudge with a bare CR (fresh prompt / retry)
            self.send("\r")
        fail("could not log in as root over serial")

    def screendump(self, path):
        s = self._connect(self.monsock, tries=10)
        s.sendall(f"screendump {path}\n".encode())
        time.sleep(1.0)
        s.close()

    def poweroff(self, grace=25):
        if self.qemu.poll() is not None:
            return
        try:
            self.send("poweroff\r")
        except OSError:
            pass
        try:
            self.qemu.wait(timeout=grace)
        except subprocess.TimeoutExpired:
            self.qemu.kill()
            self.qemu.wait()

    def run(self):
        args = self.args
        testdisk = None
        staging = None
        if args.payload or (args.cmd and not args.raw):
            staging = tempfile.mkdtemp(prefix="x86_qemu-payload-")
            if args.payload:
                for entry in os.listdir(args.payload):
                    src = os.path.join(args.payload, entry)
                    dst = os.path.join(staging, entry)
                    if os.path.isdir(src):
                        shutil.copytree(src, dst)
                    else:
                        shutil.copy2(src, dst)
            with open(os.path.join(staging, "minix-harness.sh"), "w") as f:
                f.write(GUEST_DRIVER)
            with open(os.path.join(staging, "harness-cmds.txt"), "w") as f:
                for c in args.cmd:
                    f.write(c + "\n")
            # Conservative ext2 for MINIX's libSFFS-era ext2 server:
            # 4K blocks (it rejects block sizes below PAGE_SIZE),
            # 128-byte inodes, minimal feature set. The image must
            # live OUTSIDE the staging dir (mke2fs -d populates from it).
            fd, testdisk = tempfile.mkstemp(prefix="x86_qemu-disk-", suffix=".img")
            os.close(fd)
            os.unlink(testdisk)
            mk = ["mke2fs", "-F", "-q", "-t", "ext2", "-b", "4096",
                  "-I", "128", "-O", "filetype,sparse_super", "-m", "0",
                  "-d", staging, testdisk, "64M"]
            r = subprocess.run(mk, capture_output=True, text=True)
            if r.returncode != 0:
                fail(f"mke2fs failed: {r.stderr.strip()}")

        self.spawn(testdisk)
        # --timeout is the budget for the whole session (boot, login and
        # all commands); each wait gets whatever is left of it.
        deadline = time.time() + args.timeout
        left = lambda: max(1.0, deadline - time.time())
        try:
            self.login(left())
            self.send("export TERM=vt100; export PATH=/sbin:/bin:/usr/sbin:/usr/bin\r")
            time.sleep(0.5)
            self.pump(1.0)

            if args.raw:
                # raw probe mode: run commands directly on the login shell,
                # no test disk; completion detected via per-command marker.
                for i, c in enumerate(args.cmd):
                    self.send(f"{c}; echo H:RC{i}:$?\r")
                    self.wait_re(rf"H:RC{i}:\d", left(), f"raw command {i}")
            elif testdisk:
                # virtio test disk gets the c1 controller series (block
                # major 8, unused in QEMU where there is no 2nd IDE bus).
                # NOTE: a virtio_blk instance serves only minors 0..4, i.e.
                # drive 0 of its series -> the node must be c1d0 (not c1dN).
                # at_wini's second instance may own major 8; retire it first.
                dev = "/dev/c1d0"
                self.send("minix-service down at_wini_1 2>/dev/null; "
                          "minix-service -c up /service/virtio_blk "
                          f"-dev {dev} -label virtio_blk_t -args instance=0; "
                          "echo H:VIRT:$?\r")
                self.wait_re(r"H:VIRT:\d", 90, "virtio_blk service start")
                if "H:VIRT:0" not in self.buf:
                    fail("virtio_blk service failed to start (see log)")
                self.send(f"mkdir -p /mnt; mount {dev} /mnt; echo H:MOUNT:$?\r")
                try:
                    self.wait_re(r"H:MOUNT:\d", 90, "ext2 mount")
                except SystemExit:
                    print("x86_qemu: mount of the test disk hung or failed; "
                          "check the log")
                    raise
                if "H:MOUNT:0" not in self.buf:
                    fail(f"mount {dev} returned non-zero (see log)")
                self.send("sh /mnt/minix-harness.sh || echo HARNESS:FAIL:MOUNT\r")
                self.wait_re(r"HARNESS:DONE:\d", left(), "harness completion")

            if args.screendump:
                self.screendump(args.screendump)

            # Evaluate gate
            ok = True
            for m in re.finditer(r"HARNESS:CMD:RC:(\d+):", self.buf):
                if m.group(1) != "0":
                    ok = False
            for m in re.finditer(r"H:RC\d+:(\d+)", self.buf):
                if m.group(1) != "0":
                    ok = False
            for pat in args.expect:
                if pat not in self.buf:
                    print(f"x86_qemu: MISSING expected text: {pat!r}")
                    ok = False
            # Match markers only as OUTPUT lines: marker text that appears in
            # the sent command lines gets echoed by the tty and must not
            # count (e.g. "|| echo HARNESS:FAIL:MOUNT").
            if re.search(r"[\r\n]HARNESS:FAIL", self.buf):
                ok = False
            return ok
        finally:
            if args.screendump:
                try:
                    self.screendump(args.screendump)
                except OSError:
                    pass
            if not args.keep:
                self.poweroff()
            self.logf.close()
            shutil.rmtree(self.sockdir, ignore_errors=True)
            if staging:
                shutil.rmtree(staging, ignore_errors=True)
            if testdisk and os.path.exists(testdisk):
                os.unlink(testdisk)


def main():
    ap = argparse.ArgumentParser(
        prog="x86_qemu.py",
        description="Headless MINIX i386 QEMU test harness (see header comment).")
    ap.add_argument("--image", default=os.path.join(REPO, "minix_x86.img"))
    ap.add_argument("--bootdir",
                    default=os.path.join(OBJ, "destdir.i386", "boot", "minix", ".temp"))
    ap.add_argument("--payload")
    ap.add_argument("--cmd", action="append", default=[])
    ap.add_argument("--expect", action="append", default=[])
    ap.add_argument("--timeout", type=int, default=240)
    ap.add_argument("--screendump")
    ap.add_argument("--log", default="x86_qemu.log")
    ap.add_argument("--keep", action="store_true")
    ap.add_argument("--raw", action="store_true",
                    help="run --cmd directly on the login shell; no test disk")
    args = ap.parse_args()

    for tool in ("qemu-system-i386", "mke2fs"):
        if shutil.which(tool) is None:
            fail(f"{tool} not found in PATH")
    if not os.path.exists(args.image):
        fail(f"image {args.image} not found (build it with releasetools/x86_hdimage.sh)")

    qm = QemuMinix(args)
    ok = qm.run()
    print("x86_qemu: GATE:", "PASS" if ok else "FAIL")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
